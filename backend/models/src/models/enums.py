class UnplacedReason(StrEnum):
    """Why a piece of accepted work could not be scheduled.

    Attributes:
        OUT_OF_RADIUS: No assistant lives within the configured radius of it.
        NOT_A_WORKING_DAY: Nobody near enough works that day of the week.
        NO_ASSISTANT_AVAILABLE: Everybody near enough is absent that day.
        OUTSIDE_WORKING_DAY: Its window falls outside the working day.
        MISSING_CERTIFICATION: No field employee holds every qualification the
            work requires, unexpired on the day it happens.
        MISSING_SKILL: No field employee declares every skill the work
            requires, unexpired on the day it happens.
        CUSTOMER_CONFLICT: The customer has overlapping visits that cannot all
            fit without one starting before another ends.
        NO_FEASIBLE_SLOT: It could not be fitted around the rest of the plan —
            travel, lunch and the other visits together leave no room.

    Notes:
        - The reasons are ordered from most to least specific, and the checker
          reports the first that applies. "Out of radius" and "no feasible slot"
          are both true of a visit nobody can reach, but only the first tells a
          planner what to change.
        - :attr:`MISSING_CERTIFICATION` is tested **second**, ahead of anything
          geographical. A visit nobody is qualified for is also a visit nobody
          within the radius can take, and reporting the distance would send a
          manager to widen a radius that was never the problem. "Nobody here
          holds DEAES" names a hire, a training course or a wrong requirement —
          all things somebody can act on this afternoon.
        - :attr:`MISSING_SKILL` follows it, ahead of anything geographical for
          the same reason and *behind* the certification for a different one:
          the two are fixed by different people. A missing certification is a
          hire or a training course; a missing skill may be nothing more than
          somebody who can already do the work not having said so on their own
          screen. Reporting the certification first puts the harder problem in
          front of the manager, and a run blocked by both is blocked by the
          certification whatever the skills say.
        - :attr:`NOT_A_WORKING_DAY` is tested ahead of
          :attr:`NO_ASSISTANT_AVAILABLE`, and the two are genuinely different
          answers. "Nobody works Sundays" is a recruitment or a rota decision;
          "everybody is on leave that week" resolves itself on its own. Folding
          them together would report the second when the first is true, and send
          a manager looking through absence records for a day nobody had ever
          agreed to work.
        - What is *not* here: a window narrower than the service it holds has no
          member, because
          :class:`~models.planning.intervention.intervention_requirement.InterventionRequirement`
          refuses to build one. A reason that can never be reported would be a
          branch nothing exercises.
    """

    OUT_OF_RADIUS = "out-of-radius"
    NOT_A_WORKING_DAY = "not-a-working-day"
    NO_ASSISTANT_AVAILABLE = "no-assistant-available"
    OUTSIDE_WORKING_DAY = "outside-working-day"
    MISSING_CERTIFICATION = "missing-certification"
    MISSING_SKILL = "missing-skill"
    CUSTOMER_CONFLICT = "customer-conflict"
    NO_FEASIBLE_SLOT = "no-feasible-slot"

    @classmethod
    def values(cls) -> Tuple[str, ...]:
        """Return every unplaced-reason value.

        Returns:
            Tuple[str, ...]: The eight reasons work can go unplaced.
        """
        return tuple(reason.value for reason in cls)


