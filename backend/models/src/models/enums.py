@unique
class ServiceCategory(StrEnum):
    """Enumeration for the VAT category an intervention type falls under.

    Attributes:
        NECESSITY (str): Service delivered for a necessity reason, taxed at the
            reduced 5.5% VAT rate.
        COMFORT (str): Service delivered for a comfort reason, taxed at the
            standard 20% VAT rate.

    Notes:
        The category is carried by the intervention type rather than by the
        quote line: a given type of care is structurally one or the other. A
        type that would need both categories must be split into two types.
    """

    NECESSITY = "necessity"
    COMFORT = "comfort"

    def vat_rate(self) -> Decimal:
        """Return the VAT rate applicable to this category.

        Returns:
            Decimal: ``Decimal("0.055")`` for a necessity service, and
            ``Decimal("0.20")`` for a comfort service.

        Notes:
            The rate is a :class:`~decimal.Decimal` and never a float, so it
            composes with the rest of the pricing arithmetic without losing
            cents to binary floating-point representation.
        """
        rates = {
            ServiceCategory.NECESSITY: Decimal("0.055"),
            ServiceCategory.COMFORT: Decimal("0.20"),
        }
        return rates[self]

    @classmethod
    def values(cls) -> Tuple[str, ...]:
        """Return every service-category value.

        Returns:
            Tuple[str, ...]: ``("necessity", "comfort")``.
        """
        return tuple(category.value for category in cls)


@unique
class UserRole(StrEnum):
    """Enumeration for the role granted to an authenticated account.

    Attributes:
        HCA (str): A Home Care Assistant. Declares their own availability and
            sees their own planning only.
        MANAGER (str): Sees every HCA planning, manages customers, quotes and
            the intervention-type catalog, and edits an HCA's contract type
            and certifications.
        ADMIN (str): Everything a manager can do, plus running the planning
            computation and promoting a user to manager.
        CUSTOMER (str): Somebody the agency serves, signed in to their own
            space. **Not a rung of the staff ladder** — see :meth:`rank`.
    """

    HCA = "hca"
    MANAGER = "manager"
    ADMIN = "admin"
    CUSTOMER = "customer"

    def is_staff(self) -> bool:
        """Return whether this role works for the agency.

        Returns:
            bool: ``True`` for every role but :attr:`CUSTOMER`.

        Notes:
            The one question that separates the two axes, and the only safe way
            to ask "may this account see the agency's own screens". Written as a
            method rather than repeated as ``role is not CUSTOMER`` so a fifth
            role added later cannot be admitted to the staff side by omission.
        """
        return self is not UserRole.CUSTOMER

    def rank(self) -> int:
        """Return the numeric access rank of this role.

        Returns:
            int: The access rank; a higher rank unlocks strictly more.

        Raises:
            MTRoleNotRankable: If this role is not on the staff ladder.

        Notes:
            - The ordering is shared by the whole stack so the API guards and
              any client agree on which role unlocks which feature. Rank
              comparison answers "at least a manager"; it must not be used for
              the checks that are specific to being an HCA (such as owning a
              planning), which compare the role by identity instead.
            - **:attr:`CUSTOMER` is refused rather than ranked**, and that
              refusal is the point. A customer is not above or below an
              assistant — they are a different axis. Ranked below, every
              employee would satisfy ``has_at_least(CUSTOMER)`` and a guard
              written the usual way would let staff into a household's private
              space; ranked above, a customer would satisfy the manager checks.
              There is no number that is correct, so there is no number.
        """
        ranks = {UserRole.HCA: 0, UserRole.MANAGER: 1, UserRole.ADMIN: 2}
        if self not in ranks:
            raise MTRoleNotRankable(
                f"Role {self.value!r} is not on the staff ladder and cannot be "
                f"ranked. Compare it by identity — see UserRole.is_staff."
            )
        return ranks[self]

    def has_at_least(self, minimum: UserRole) -> bool:
        """Return whether this role ranks at or above ``minimum``.

        Args:
            minimum (UserRole): The lowest role that satisfies the check.

        Returns:
            bool: ``True`` when this role's rank is greater than or equal to
            the rank of ``minimum``.

        Raises:
            MTRoleNotRankable: If either role is off the staff ladder.

        Notes:
            A customer on either side raises rather than answering. Answering
            ``False`` would be the more forgiving choice and the wrong one: the
            call is a mistake, and a mistake that returns a plausible boolean is
            one nobody finds.
        """
        return self.rank() >= minimum.rank()

    @classmethod
    def values(cls) -> Tuple[str, ...]:
        """Return every role value.

        Returns:
            Tuple[str, ...]: ``("hca", "manager", "admin", "customer")``.
        """
        return tuple(role.value for role in cls)

    @classmethod
    def staff_values(cls) -> Tuple[str, ...]:
        """Return every role that works for the agency.

        Returns:
            Tuple[str, ...]: ``("hca", "manager", "admin")``.

        Notes:
            What a staff-facing payload validates against, so a request cannot
            promote somebody into — or out of — the customer axis by naming it.
        """
        return tuple(role.value for role in cls if role.is_staff())


@unique
class QuoteStatus(StrEnum):
    """Enumeration for the lifecycle status of a quote.

    Attributes:
        DRAFT (str): Being composed; lines may still be added or removed.
        PENDING_VALIDATION (str): Submitted by an assistant and waiting for a
            manager to validate it.
        SENT (str): Sent to the customer and awaiting their answer.
        ACCEPTED (str): Accepted by the customer. Only accepted quotes feed the
            planning computation.
        REJECTED (str): Declined by the customer.
        EXPIRED (str): Its validity date passed before an answer was given.

    Notes:
        - ``PENDING_VALIDATION`` sits between the draft and the commitment. An
          assistant knows what a customer needs but does not set the agency's
          prices, so a quote they write waits for a manager before its work is
          committed. It is deliberately a status rather than a flag: a quote is in
          exactly one place at a time, and a boolean beside the status would allow
          the nonsense of an accepted quote still awaiting validation.
        - ``SENT`` is **no longer produced by any path**. Validation used to stop
          there, needing a second acceptance that nothing on any screen asked for,
          so a validated quote's work silently never reached a planning run; both
          approval paths now end at ``ACCEPTED``. The member is kept because rows
          stored in it before that change still exist, and the interface keeps its
          tab and its accept button for exactly them.
    """

    DRAFT = "draft"
    PENDING_VALIDATION = "pending-validation"
    SENT = "sent"
    ACCEPTED = "accepted"
    REJECTED = "rejected"
    EXPIRED = "expired"

    @classmethod
    def values(cls) -> Tuple[str, ...]:
        """Return every quote-status value.

        Returns:
            Tuple[str, ...]: The six supported statuses.
        """
        return tuple(status.value for status in cls)

    def is_editable(self) -> bool:
        """Return whether the lines may still be changed.

        Returns:
            bool: ``True`` only for a draft.

        Notes:
            A quote awaiting validation is frozen: a manager must decide on the
            figures they were shown, not on figures that moved underneath them
            while they read.
        """
        return self is QuoteStatus.DRAFT

    def is_awaiting_validation(self) -> bool:
        """Return whether a manager still owes this quote a decision.

        Returns:
            bool: ``True`` when the quote sits in the validation queue.
        """
        return self is QuoteStatus.PENDING_VALIDATION


@unique
class BillingPeriodicity(StrEnum):
    """Enumeration for how often an agency invoices its customers.

    Attributes:
        WEEKLY (str): One bill per ISO week, Monday to Sunday.
        MONTHLY (str): One bill per calendar month.
        YEARLY (str): One bill per calendar year.

    Notes:
        - The member decides a **window**, and the window is the whole of what
          the specification calls a time pro-rata. A
          :class:`~models.quoting.quote_line.QuoteLine` carries one
          ``service_date``, not a range: it is a single dated visit. No line can
          therefore straddle a period boundary, and "only the part of the quote
          inside the window is billed" reduces exactly to a date filter, with no
          fractional amount computed anywhere. Lines dated after the window are
          simply absent from this bill; the next period has a different window
          and picks them up unchanged.
        - **Both bounds are inclusive**, matching every other period in the
          application: ``QuoteRepository.list_schedulable``,
          ``InterventionRepository.replace_for_period`` and
          :meth:`~models.quoting.quote.Quote.covers` all read that way. An
          exclusive end here would be the one period that behaved differently,
          and the symptom would be a day's care quietly unbilled every month.
        - Stored in the database rather than in ``app.yaml``, because the
          specification puts it in the hands of a manager and a YAML value would
          need a deployment to change. See
          :class:`~models.settings.billing_settings.BillingSettings`.
    """

    WEEKLY = "weekly"
    MONTHLY = "monthly"
    YEARLY = "yearly"

    @classmethod
    def values(cls) -> Tuple[str, ...]:
        """Return every billing-periodicity value.

        Returns:
            Tuple[str, ...]: ``("weekly", "monthly", "yearly")``.
        """
        return tuple(periodicity.value for periodicity in cls)

    def window_for(self, day: Union[date, datetime]) -> Tuple[date, date]:
        """Return the billing window that contains a day.

        Args:
            day (Union[date, datetime]): Any day inside the wanted period.

        Returns:
            Tuple[date, date]: The first and last day of the period, **both
            inclusive**.

        Raises:
            MTInvalidBillingPeriodicity: If ``day`` is not a date.

        Notes:
            - The month's last day is computed as "the first of next month,
              minus one day" rather than by asking how long the month is, so
              February and a leap year need no special case and there is one
              arithmetic path instead of twelve.
            - The week is anchored on Monday, the same anchoring
              :meth:`~service.quotes.quotes.QuoteService._monday_of` derives
              from 4 January, so a weekly bill and a weekly quote aggregate
              cover the same seven days.
        """
        if not isinstance(day, date):
            raise MTInvalidBillingPeriodicity(f"Invalid day: {day!r}. Must be a date.")
        if isinstance(day, datetime):
            day = day.date()
        if self is BillingPeriodicity.WEEKLY:
            start = day - timedelta(days=day.isoweekday() - 1)
            return start, start + timedelta(days=6)
        if self is BillingPeriodicity.MONTHLY:
            start = day.replace(day=1)
            next_month = date(day.year + day.month // 12, day.month % 12 + 1, 1)
            return start, next_month - timedelta(days=1)
        return date(day.year, 1, 1), date(day.year, 12, 31)

    def previous_window(self, day: Union[date, datetime]) -> Tuple[date, date]:
        """Return the window that ends immediately before the one holding a day.

        Args:
            day (Union[date, datetime]): Any day inside the current period.

        Returns:
            Tuple[date, date]: The previous period's first and last day.

        Raises:
            MTInvalidBillingPeriodicity: If ``day`` is not a date.

        Notes:
            "Bill last month" is what an agency actually asks for — a period is
            invoiced once it has been delivered — and the arithmetic is one day
            back from the current window's start rather than a month subtracted
            from ``day``, which would land on 28 February from 31 March. Doing
            it here stops every caller getting that wrong separately.
        """
        start, _ = self.window_for(day)
        return self.window_for(start - timedelta(days=1))


@unique
class BillStatus(StrEnum):
    """Enumeration for where a bill has reached commercially.

    Attributes:
        TO_BE_VALIDATED (str): Generated, with its document, and waiting for a
            manager to approve it. Nothing has reached the customer.
        ACCEPTED (str): Approved by a manager. Approval is what sends it.
        WAITING_PAYMENT (str): Sent to the customer; the money is outstanding.
        PAID (str): Settled.

    Notes:
        - **Only a manager or an administrator moves a bill.** The status is a
          statement about money owed, and an assistant who could set one would
          be writing the agency's accounts.
        - Two things this enumeration deliberately does **not** record: whether
          a document exists — that is ``Bill.document_key`` — and whether
          generation failed, which is
          :class:`BillingRunStatus`. Folding a generation outcome in here would
          make "waiting payment" mean two unrelated things, and a manager
          reading the list could not tell a bill nobody has paid from one nobody
          managed to produce.
        - There is no ``CANCELLED``. French invoice numbering forbids both reuse
          and gaps, so a mistaken invoice is corrected by a credit note rather
          than withdrawn — and a credit note is a document in its own right, not
          a status on this one.
    """

    TO_BE_VALIDATED = "to-be-validated"
    ACCEPTED = "accepted"
    WAITING_PAYMENT = "waiting-payment"
    PAID = "paid"

    @classmethod
    def values(cls) -> Tuple[str, ...]:
        """Return every bill-status value.

        Returns:
            Tuple[str, ...]: The four supported statuses, in the order reached.
        """
        return tuple(status.value for status in cls)

    def is_terminal(self) -> bool:
        """Return whether the bill has nothing further to reach.

        Returns:
            bool: ``True`` only for :attr:`PAID`.
        """
        return self is BillStatus.PAID

    def can_move_to(self, target: BillStatus) -> bool:
        """Return whether a manager may move a bill from here to ``target``.

        Args:
            target (BillStatus): The status being asked for.

        Returns:
            bool: ``True`` when ``target`` is the next status or the previous
            one.

        Notes:
            **One step, either way.** Forward is the lifecycle; backward is the
            correction, and a manager who marked the wrong row paid needs it —
            an irreversible status would leave them editing the database.
            Anything further is refused: a bill going straight from
            :attr:`TO_BE_VALIDATED` to :attr:`PAID` would skip the record of it
            ever having been approved, and of it ever having been sent, which is
            the audit trail the four statuses exist to keep.
        """
        order = tuple(BillStatus)
        return abs(order.index(target) - order.index(self)) == 1


@unique
class BillingRunStatus(StrEnum):
    """Enumeration for the lifecycle status of a bill-generation run.

    Attributes:
        PENDING (str): Accepted and queued, not yet picked up.
        RUNNING (str): Bills are being generated.
        SUCCEEDED (str): Every customer with billable work was billed.
        PARTIAL (str): Some customers were billed and some failed.
        FAILED (str): The run ended on an error; see the run's error message.

    Notes:
        Deliberately not :class:`PlanningRunStatus`, whose members mean
        something else: there, :attr:`PARTIAL` describes visits that could not
        be placed. Here it describes customers who could not be billed, and one
        enumeration answering to two vocabularies is how a status chip ends up
        telling somebody the wrong thing.
    """

    PENDING = "pending"
    RUNNING = "running"
    SUCCEEDED = "succeeded"
    PARTIAL = "partial"
    FAILED = "failed"

    @classmethod
    def values(cls) -> Tuple[str, ...]:
        """Return every billing-run-status value.

        Returns:
            Tuple[str, ...]: The five supported statuses.
        """
        return tuple(status.value for status in cls)

    def is_terminal(self) -> bool:
        """Return whether no further status change can follow this one.

        Returns:
            bool: ``True`` for :attr:`SUCCEEDED`, :attr:`PARTIAL` and
            :attr:`FAILED`.

        Notes:
            Clients poll a run until this returns ``True``. A partial run is
            finished — the bills that could be written are written — so a client
            that kept polling would wait forever.
        """
        return self in (
            BillingRunStatus.SUCCEEDED,
            BillingRunStatus.PARTIAL,
            BillingRunStatus.FAILED,
        )


@unique
class RecipientKind(StrEnum):
    """Enumeration for what kind of party an invoice is addressed to.

    Attributes:
        INDIVIDUAL (str): A private person — the household being cared for.
        BUSINESS (str): A company: a mutuelle, a pension fund, an employer.
        PUBLIC (str): A public body: a conseil départemental, a CCAS.

    Notes:
        - **This decides which regulatory regime the invoice falls under**, not
          merely how it is addressed. An individual means *e-reporting*: the
          transaction is declared to the tax authority and the customer receives
          whatever the agency already sends them. A business or a public body
          means *e-invoicing*: a structured document routed through a platform,
          which the recipient's own system reads. Getting the kind wrong sends
          the invoice down the wrong path entirely.
        - The two non-individual kinds are kept apart even though both are
          e-invoicing, because a public body routes by an additional service
          code and is reached through a different platform. Folding them into
          one "professional" kind would lose the only distinction that changes
          where the document goes.
        - A household has no SIREN, and that is a fact rather than missing data.
          It is why the identifier is optional on the recipient and required by
          the other two kinds — see
          :class:`~models.billing.bill_recipient.BillRecipient`.
    """

    INDIVIDUAL = "individual"
    BUSINESS = "business"
    PUBLIC = "public"

    @classmethod
    def values(cls) -> Tuple[str, ...]:
        """Return every recipient kind.

        Returns:
            Tuple[str, ...]: ``("individual", "business", "public")``.
        """
        return tuple(kind.value for kind in cls)

    def requires_legal_identifier(self) -> bool:
        """Return whether this kind of recipient must carry a SIREN.

        Returns:
            bool: ``True`` for a business or a public body.

        Notes:
            A structured invoice addressed to a professional is routed on that
            identifier, so one without it cannot be delivered at all. A private
            individual has none to give, which is why the field is optional on
            the model and this is what makes it required where it applies.
        """
        return self is not RecipientKind.INDIVIDUAL

    def requires_electronic_invoice(self) -> bool:
        """Return whether this recipient must be sent a structured invoice.

        Returns:
            bool: ``True`` for a business or a public body.

        Notes:
            The mirror of it is just as load-bearing: a ``False`` here means the
            invoice is **reported**, not transmitted, and a home-care agency's
            revenue is mostly of that kind. Asking this rather than testing
            ``kind is INDIVIDUAL`` at each call site is what keeps the reform's
            own vocabulary in the code.
        """
        return self.requires_legal_identifier()


@unique
class OperationNature(StrEnum):
    """Enumeration for what an invoice covers: goods, services, or both.

    Attributes:
        GOODS (str): A supply of goods.
        SERVICES (str): A supply of services.
        MIXED (str): Both, on one document.

    Notes:
        - A **mandatory mention** on a French invoice, and one this agency would
          otherwise never have written down: everything it sells is a service,
          so the value is constant today. It is stored rather than assumed
          because a constant that is never recorded is a constant nobody
          notices changing — the day the agency starts invoicing equipment, an
          implicit "services" would be a false declaration on every line of it.
        - It also decides when VAT falls due. On services the tax is exigible on
          **collection**, which is why a bill reaching
          :attr:`BillStatus.PAID` is a reportable event and not merely an
          accounting nicety.
    """

    GOODS = "goods"
    SERVICES = "services"
    MIXED = "mixed"

    @classmethod
    def values(cls) -> Tuple[str, ...]:
        """Return every operation nature.

        Returns:
            Tuple[str, ...]: ``("goods", "services", "mixed")``.
        """
        return tuple(nature.value for nature in cls)

    def includes_services(self) -> bool:
        """Return whether any part of the invoice is a supply of services.

        Returns:
            bool: ``True`` for services and for a mixed operation.

        Notes:
            Asked when deciding whether the collection date has to be reported.
            A mixed invoice counts, because the services on it are exigible on
            collection whatever the goods beside them do.
        """
        return self in (OperationNature.SERVICES, OperationNature.MIXED)


